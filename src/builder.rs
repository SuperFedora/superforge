pub fn ansi_rgb(rgb: (u8, u8, u8)) -> String {
    format!("\x1b[38;2;{};{};{}m", rgb.0, rgb.1, rgb.2)
}

pub fn print_status_and_charts(st: &ForgeState) {
    let p = ansi_rgb(st.pri_rgb);
    let s = ansi_rgb(st.sec_rgb);
    let b = "\x1b[1m";
    let r = "\x1b[0m";
    let hw = &st.hw;

    println!("SuperFedora Forge — Hardware-Tuned Source Builder & Firefox WebApp Engine");
    println!("  CPU Model    : {}", hw.cpu_model);
    println!("  Target Arch  : -march={} ({}, {} threads)", hw.march_target, hw.cpu_arch, hw.cpu_jobs);
    println!("  SIMD / ISA   : {}", hw.isa_flags);
    println!("  Fast Linker  : {}", hw.linker);
    println!("  GPU Device   : {}", hw.gpu_info);
    println!("  CFLAGS       : {}", hw.host_cflags);
    println!("  RUSTFLAGS    : {}\n", hw.host_rustflags);

    println!("  PRESET       BINARY            STATUS");
    println!("  ------       ------            ------");
    for it in &st.items {
        let status = if it.installed {
            format!("forged ({})", hw.march_target)
        } else {
            "not-forged".into()
        };
        println!("  {:<12} {:<17} [{}]", it.name, it.bin_name, status);
    }

    println!("\n{p}{b}━━ SUPERFORGE NATIVE (-march=native) BINARIES & SIZE CHART{r}");
    let max_kb = st.items.iter().map(|i| i.size_kb).max().unwrap_or(1).max(1);
    for item in &st.items {
        let status = if item.installed { "\x1b[1;32m[FORGED]\x1b[0m" } else { "\x1b[2m[AVAIL ]\x1b[0m" };
        let ratio = (((item.size_kb as f64).sqrt() * 100.0) / (max_kb as f64).sqrt()).min(100.0) as usize;
        let filled = ((ratio * 18) / 100).max(usize::from(item.installed));
        let bar = format!(
            "{}{}\x1b[38;5;238m{}\x1b[0m",
            if item.installed { &p } else { "\x1b[2m" },
            "█".repeat(filled),
            "░".repeat(18usize.saturating_sub(filled))
        );
        let sz_str = if item.size_kb > 0 { format!("{:>6} KB", item.size_kb) } else { "     --  ".into() };
        println!("  {} {s}{b}{:<13}{r} {:<6} {} {}  \x1b[2m{}\x1b[0m", status, item.name, item.kind, bar, sz_str, item.desc);
    }

    if !st.webapps.is_empty() {
        println!("\n  WEBAPP       APP ID                  PROFILE    URL");
        println!("  ------       ------                  -------    ---");
        for (aid, name, prof, url) in &st.webapps {
            let short: String = name.chars().take(12).collect();
            println!("  {:<12} {:<23} {:<10} {}", short, aid, prof, url);
        }
    }
}

pub fn write_hw_profile(st: &ForgeState) -> PathBuf {
    let _ = fs::create_dir_all(&st.state_dir);
    let _ = fs::create_dir_all(st.state_dir.join("source-built"));
    let hw = &st.hw;
    let hw_env = st.state_dir.join("hardware-flags.env");
    let content = format!(
        "# Generated by SuperForge Localhost Source Builder\nSF_CPU_MODEL=\"{}\"\nSF_CPU_ARCH=\"{}\"\nSF_MARCH_TARGET=\"{}\"\nSF_CPU_JOBS=\"{}\"\nSF_ISA_FLAGS=\"{}\"\nexport CFLAGS=\"{}\"\nexport CXXFLAGS=\"{}\"\nexport LDFLAGS=\"{}\"\nexport RUSTFLAGS=\"{}\"\nexport MAKEFLAGS=\"-j{}\"\nexport CARGO_BUILD_JOBS=\"{}\"\nexport CMAKE_BUILD_PARALLEL_LEVEL=\"{}\"\n",
        hw.cpu_model, hw.cpu_arch, hw.march_target, hw.cpu_jobs, hw.isa_flags,
        hw.host_cflags, hw.host_cflags, hw.host_ldflags, hw.host_rustflags,
        hw.cpu_jobs, hw.cpu_jobs, hw.cpu_jobs
    );
    let _ = fs::write(&hw_env, content);
    let _ = fs::write(st.state_dir.join("build-mode"), "source\n");
    let home = env::var("HOME").unwrap_or_else(|_| "/home/jeryd".into());
    let rpmmacros = PathBuf::from(home).join(".rpmmacros");
    let existing = fs::read_to_string(&rpmmacros).unwrap_or_default();
    if !existing.contains("SuperFedora localhost") {
        let extra = format!(
            "\n# SuperFedora localhost hardware optimization profile ({})\n%_smp_mflags -j{}\n%optflags {}\n",
            hw.march_target, hw.cpu_jobs, hw.host_cflags
        );
        let _ = fs::write(&rpmmacros, format!("{existing}{extra}"));
    }
    hw_env
}

pub fn exec_runner(st: &mut ForgeState, args: &[String]) -> i32 {
    let runner = st.forge_root.join("lib/forge-runner.sh");
    let code = Command::new(runner)
        .env("FORGE_ROOT", &st.forge_root)
        .args(args)
        .status()
        .map(|s| s.code().unwrap_or(0))
        .unwrap_or(1);
    st.refresh();
    code
}

pub fn run_update_graphical(st: &mut ForgeState, extra_args: &[String]) -> i32 {
    if extra_args.iter().any(|a| a == "--dry-run" || a == "-n") {
        let mut all = vec!["update".to_string()];
        all.extend_from_slice(extra_args);
        return exec_runner(st, &all);
    }
    let p = ansi_rgb(st.pri_rgb);
    let s = ansi_rgb(st.sec_rgb);
    let b = "\x1b[1m";
    let r = "\x1b[0m";
    println!("{p}{b}╔══════════════════════════════════════════════════════════════════════════════╗{r}");
    println!("{p}{b}║  [::] SUPERFORGE 4-STAGE UPDATE PIPELINE (DNF + GIT + LTO + WEBAPPS)         ║{r}");
    println!("{p}{b}╚══════════════════════════════════════════════════════════════════════════════╝{r}");

    let runner = st.forge_root.join("lib/forge-runner.sh");
    let mut cmd = Command::new(&runner);
    cmd.env("FORGE_ROOT", &st.forge_root).arg("update").args(extra_args).stdout(Stdio::inherit()).stderr(Stdio::inherit());
    let Ok(mut child) = cmd.spawn() else { return 1 };
    loop {
        match child.try_wait() {
            Ok(Some(status)) => {
                st.refresh();
                println!("\n  {s}{b}Forge Pipeline{r} {p}████████████████████████████████████{r} \x1b[1m100%\x1b[0m  \x1b[1;32m[COMPLETE]\x1b[0m");
                let _ = io::stdout().flush();
                return status.code().unwrap_or(0);
            }
            Ok(None) => thread::sleep(Duration::from_millis(250)),
            Err(_) => return 1,
        }
    }
}
